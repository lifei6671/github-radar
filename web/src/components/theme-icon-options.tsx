export function ThemeIcon({ icon, color, size = 15 }: { icon?: string; color?: string; size?: number }) {
  if (!icon || !Object.hasOwn(themeIcons, icon)) return null
  const Icon = themeIcons[icon as keyof typeof themeIcons].glyph
  return <span className="theme-icon" data-color={color || undefined} data-icon={icon} aria-hidden="true">
    <Icon size={size} />
  </span>
}
