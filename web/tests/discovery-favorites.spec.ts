test('后台保存发现页标签和精选门槛，返回前台等待新结果', async ({ page }) => {
  await mockRadar(page)
  await session(page)
  await page.goto('/admin')
  const returnToPublic = page.getByRole('link', { name: '返回前台', exact: true })
  await returnToPublic.click()
  const previous = page.getByRole('region', { name: '项目动态' }).getByRole('link', { name: 'vercel/ai' })
  await expect(previous).toBeVisible()
  await page.goBack()
  await page.getByRole('link', { name: '运行状态', exact: true }).click()
  await page.getByRole('link', { name: '发现页标签', exact: true }).click()
  await page.getByRole('button', { name: '编辑标签 AI 编程' }).click()
  const name = page.getByRole('textbox', { name: 'AI 编程的标签名称' })
  await name.fill('代码智能体')
  await page.getByRole('heading', { name: '发现页标签' }).hover()
  await expect(name).toBeFocused()
  await name.press('Tab')
  await expect(name).toHaveCount(0)
  await expect(page.getByRole('button', { name: '编辑标签 代码智能体' })).toBeVisible()
  await page.getByRole('button', { name: '移除 AI 多媒体' }).click()
  await page.getByRole('button', { name: '移除 其他' }).click()
  await page.getByRole('button', { name: '添加标签' }).click()
  const add = page.getByRole('dialog', { name: '添加标签' })
  await add.getByRole('combobox', { name: '选择分类' }).selectOption('media')
  await add.getByRole('button', { name: '添加', exact: true }).click()
  await dragSetting(page, '代码智能体', 'AI 智能体')
  const top = page.getByRole('spinbutton', { name: '全站日榜入选名次' })
  await expect(top).toHaveValue('10')
  await top.fill('6')
  const heat = page.getByRole('spinbutton', { name: '热度权重（%）' })
  const freshness = page.getByRole('spinbutton', { name: '新鲜度权重（%）' })
  const consecutive = page.getByRole('spinbutton', { name: '连续上榜天数' })
  const cooldown = page.getByRole('spinbutton', { name: '冷却天数', exact: true })
  await expect(heat).toHaveValue('70')
  await expect(freshness).toHaveValue('30')
  await expect(consecutive).toHaveValue('3')
  await expect(cooldown).toHaveValue('2')
  await heat.fill('45')
  await expect(freshness).toHaveValue('55')
  await freshness.fill('60')
  await expect(heat).toHaveValue('40')
  await consecutive.fill('5')
  await cooldown.fill('0')
  const savedRequest = page.waitForRequest((request) =>
    request.method() === 'PUT' && request.url().endsWith('/api/v1/system/discovery-tabs'))
  await page.getByRole('button', { name: '保存配置' }).click()
  expect((await savedRequest).postDataJSON().ranking).toEqual({ heatWeight: 40, freshnessWeight: 60, consecutiveDays: 5, cooldownDays: 0 })
  await expect(page.getByText('已保存', { exact: true })).toBeVisible()
  await expect(top).toHaveValue('6')

  let started!: () => void
  let release!: () => void
  const requested = new Promise<void>((resolve) => { started = resolve })
  const ready = new Promise<void>((resolve) => { release = resolve })
  await page.route(/\/api\/v1\/public\/discovery\?/, async (route) => {
    started()
    await ready
    await route.fallback()
  })
  await returnToPublic.click()
  await requested
  await expect(previous).toHaveCount(0)
  await expect(page.getByRole('region', { name: '当前热点' })).toHaveCount(0)
  release()
  const tabs = page.getByRole('group', { name: '项目分类' })
  await expect(tabs.getByRole('button')).toHaveText(['全部', '代码智能体', 'AI 智能体', 'MCP', '开发者工具', 'AI 多媒体'])
  await tabs.getByRole('button', { name: '代码智能体' }).click()
  await expect(page).toHaveURL(/\/discover\/coding$/)
  await expect(tabs.getByRole('button', { name: '代码智能体' })).toHaveAttribute('aria-pressed', 'true')

  await page.goto('/discover/other')
  await expect(page).toHaveURL(/\/$/)
  await expect(tabs.getByRole('button', { name: '代码智能体' })).toBeVisible()
  await expect(tabs.getByRole('button', { name: '全部', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/repos')
  await expect(tabs.getByRole('link', { name: 'AI 编程' })).toBeVisible()
  await expect(tabs.getByRole('link', { name: '其他', exact: true })).toBeVisible()
  await page.goto('/admin/runs?tab=discovery-tabs')
  await expect(heat).toHaveValue('40')
  await expect(freshness).toHaveValue('60')
  await expect(consecutive).toHaveValue('5')
  await expect(cooldown).toHaveValue('0')
})

