test('发现页与全部项目共用匿名收藏，并在同一浏览器中跨标签页同步', async ({ page, browser }) => {
  const radar = await mockRadar(page)
  radar.moveDiscoveryAcrossCursor()
  await page.goto('/')
  const discover = page.getByRole('region', { name: '项目动态' }).locator('.repo-row-head')
  const add = discover.getByRole('button', { name: '收藏 vercel/ai', exact: true })
  await expect(add).toHaveAttribute('aria-pressed', 'false')
  await expect(discover.getByRole('button', { name: '收藏 astral-sh/ruff', exact: true })).toHaveCount(0)
  await add.click()
  const saved = discover.getByRole('button', { name: '取消收藏 vercel/ai', exact: true })
  await expect(saved).toHaveAttribute('aria-pressed', 'true')
  const timeline = page.getByRole('region', { name: '项目动态' })
  await timeline.getByRole('button', { name: '加载更多' }).click()
  const olderRepo = timeline.locator('.timeline-item').filter({ has: page.getByRole('link', { name: 'charmbracelet/gum', exact: true }) })
  await expect(olderRepo.getByRole('link', { name: 'charmbracelet/gum' })).toBeVisible()
  await expect(timeline.getByRole('heading', { name: /11月10日/ })).toBeVisible()
  await expect(olderRepo.locator('.timeline-clock time')).toHaveAttribute('datetime', '2026-11-10T12:00:00Z')
  await expect(olderRepo.locator('.repo-card time')).toHaveAttribute('datetime', '2026-11-11T12:00:00Z')
  await expect(saved).toHaveCount(1)
  await page.getByRole('group', { name: '项目分类' }).getByRole('button', { name: 'AI 编程', exact: true }).click()
  await expect(page).toHaveURL(/\/discover\/coding$/)
  await expect(saved).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/repos')
  const remove = page.getByRole('button', { name: '取消收藏 vercel/ai', exact: true })
  await expect(remove).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: '收藏 astral-sh/ruff', exact: true })).toBeVisible()
  await page.reload()
  await expect(remove).toHaveAttribute('aria-pressed', 'true')

  const url = new URL('/starred', page.url()).href
  const isolated = await browser.newContext()
  try {
    const other = await isolated.newPage()
    await mockRadar(other)
    await other.goto(url)
    await expect(other.getByText('还没有收藏的仓库')).toBeVisible()
  } finally {
    await isolated.close()
  }

  const tab = await page.context().newPage()
  const list = await mockRadar(tab)
  await tab.goto(url)
  await expect(tab.getByRole('heading', { name: '我的收藏' })).toBeVisible()
  await expect(tab.getByText('收藏保存在此浏览器', { exact: false })).toBeVisible()
  const row = tab.getByRole('list', { name: '收藏仓库' }).getByRole('listitem')
  await expect(row.getByRole('link', { name: 'vercel/ai' })).toHaveAttribute('href', '/repos/vercel/ai?repoId=1')
  await expect(row).toHaveCSS('border-radius', '12px')
  await expect(row.locator('time')).toBeVisible()
  await tab.setViewportSize({ width: 390, height: 844 })
  await expect(row).toHaveCSS('border-top-width', '0px')
  await expect(row.locator('time')).toBeHidden()
  expect(await tab.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  list.setSummaryMissing(1)
  await tab.reload()
  await expect(tab.getByText('暂无可展示的收藏')).toBeVisible()
  await expect(row).toHaveCount(0)
  list.restoreSummary(1)
  await tab.reload()
  await expect(row.getByRole('link', { name: 'vercel/ai' })).toBeVisible()
  list.renameFirstRepo('vercel/ai-toolkit')
  list.setRepoName(2, 'vercel/ai')
  await tab.goto(new URL('/repos/vercel/ai?repoId=1', url).href)
  await expect(tab).toHaveURL(/\/repos\/vercel\/ai-toolkit$/)
  await expect(tab.getByRole('heading', { name: 'vercel/ai-toolkit', exact: true })).toBeVisible()
  await tab.goto(url)
  await row.getByRole('button', { name: '取消收藏 vercel/ai', exact: true }).click()
  await expect(tab.getByText('还没有收藏的仓库')).toBeVisible()
  await expect(page.getByRole('button', { name: '收藏 vercel/ai', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect([...radar.requests, ...list.requests].every((request) => request.startsWith('GET '))).toBe(true)
  await page.getByRole('link', { name: '收藏', exact: true }).click()
  await expect(page).toHaveURL(/\/starred$/)
})
