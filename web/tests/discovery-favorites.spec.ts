test('发现与全部项目共用精选标记，采样时间和热度级别在卡片右侧', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const mock = await mockRadar(page)
  mock.setSummaryTitle(1, '统一模型调用工具包')
  mock.setSummaryTitle(4, null)
  await page.goto('/')
  const card = (name: string) => page.locator('.repo-card').filter({ has: page.getByRole('link', { name, exact: true }) })
  const featured = card('vercel/ai')
  const reason = featured.locator('.repo-card-reason')
  await expect(featured.locator('.repo-title')).toHaveText('统一模型调用工具包')
  await expect(featured.locator('.repo-summary')).toContainText('项目提供了统一的模型调用与流式输出接口')
  await expect(featured.getByText('精选', { exact: true })).toBeVisible()
  await expect(reason).toContainText('应用开发者可借鉴它的统一接口来复用工具调用流程。')
  await expect(card('openai/codex').locator('.repo-card-reason')).toContainText('维护大型仓库的开发者可以参考它如何在终端里审阅和应用补丁。')
  await expect(featured.locator('.repo-card-categories a')).toHaveCount(0)
  await expect(reason).toHaveCSS('border-top-style', 'solid')
  await expect(featured.getByText(/采样于/)).toHaveCount(0)
  const sample = featured.locator('time')
  await expect(sample).toHaveAttribute('datetime', '2026-11-11T12:00:00Z')
  const [timeBox, gradeBox, favoriteBox, sourceBox] = await Promise.all([
    sample.boundingBox(), featured.getByText('S 级', { exact: true }).boundingBox(),
    featured.getByRole('button', { name: '收藏 vercel/ai' }).boundingBox(), featured.locator('.repo-row-head .repo-tags').boundingBox(),
  ])
  expect(timeBox!.x + timeBox!.width).toBeGreaterThanOrEqual(favoriteBox!.x + favoriteBox!.width - 1)
  expect(gradeBox!.x).toBeGreaterThan(sourceBox!.x + sourceBox!.width)
  expect(gradeBox!.x + gradeBox!.width).toBeLessThan(favoriteBox!.x)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '全部项目' }).click()
  await expect(page).toHaveURL(/\/repos$/)
  await expect(featured.getByText('精选', { exact: true })).toBeVisible()
  await expect(reason).toContainText('应用开发者可借鉴它的统一接口来复用工具调用流程。')
  const metadata = featured.locator('.repo-card-categories a')
  await expect(metadata).toHaveText(['AI 编程', '#开发工具', '#流式响应', '#工具调用'])
  await expect(metadata.first()).toHaveAttribute('href', '/categories/coding')
  await expect(metadata.first()).toHaveCSS('border-top-width', '0px')
  await expect(metadata.nth(2)).toHaveAttribute('href', '/repos?tag=' + encodeURIComponent('流式响应'))
  const withoutReason = card('modelcontextprotocol/servers')
  await expect(withoutReason.getByText('精选', { exact: true })).toBeVisible()
  await expect(withoutReason.locator('.repo-card-reason')).toHaveCount(0)
  await expect(withoutReason.locator('.repo-title')).toHaveCount(0)
  await expect(withoutReason.locator('.repo-summary')).toBeVisible()
  const ordinary = card('astral-sh/ruff')
  await expect(ordinary).toBeVisible()
  await expect(ordinary.getByText('精选', { exact: true })).toHaveCount(0)
  await expect(ordinary.locator('.repo-card-reason')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(reason).toHaveCSS('text-overflow', 'ellipsis')
  await metadata.nth(2).click()
  const clearTag = page.getByRole('button', { name: '清除标签筛选 流式响应' })
  await expect(clearTag).toBeVisible()
  await expect(ordinary).toHaveCount(0)
  await clearTag.click()
  await expect(page).toHaveURL(/\/repos$/)
  await expect(clearTag).toHaveCount(0)
  await expect(ordinary).toBeVisible()
})

