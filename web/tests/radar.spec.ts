for (const status of [200, 401] as const) {
  test('延迟保存响应 ' + status + ' 与新会话隔离', async ({ page }) => {
    const fixture = await mockRadar(page)
    await loginFromSettings()
    await page.getByLabel('模型', { exact: true }).fill('old-session-draft')
    const delayed = fixture.delaySave(status)
    await page.getByRole('button', { name: '保存配置' }).click()
    await delayed.started
    await expect(page.getByLabel('模型', { exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '退出会话' }).click()
    await loginFromSettings(false)
    const currentModel = page.getByLabel('模型', { exact: true })
    await expect(currentModel).toHaveValue('fixture-model')
    const response = page.waitForResponse((item) => item.request().method() === 'PUT' && item.url().endsWith('/system/settings'))
    delayed.release()
    await response
    await expect(currentModel).toHaveValue('fixture-model')
    await expect(page.getByText('已保存', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('heading', { name: '连接 GitHub 雷达' })).toHaveCount(0)

    async function loginFromSettings(navigate = true) {
      if (navigate) await page.goto('/system?tab=runtime')
      await login(page)
      await page.locator('summary').filter({ hasText: 'AI 中文摘要' }).click()
    }
  })
}

