test('日聚合长窗绘制孤立的有效 Star 观测', async ({ page }) => {
  await mockRadar(page)
  await session(page)
  await page.goto('/repos/1?range=180d')
  const canvas = page.getByRole('img', { name: '累计 Star 趋势，缺测点断开' }).locator('canvas')
  await expect(canvas).toBeVisible()
  // 网格与坐标标签是中性色，只有实际 Star 数据使用青绿色。
  await expect.poll(() => canvas.evaluate((element: HTMLCanvasElement) => {
    const pixels = element.getContext('2d')!.getImageData(0, 0, element.width, element.height).data
    for (let offset = 0; offset < pixels.length; offset += 4) {
      if (pixels[offset + 3] > 100 && pixels[offset + 1] - pixels[offset] > 35 && pixels[offset + 2] - pixels[offset] > 25) return true
    }
    return false
  })).toBeTruthy()
})

for (const [width, height] of [[390, 844], [768, 1024], [1440, 900], [1920, 1080]]) {
  test('亮暗主题和导航在 ' + width + 'px 不溢出', async ({ page }, info) => {
    await page.setViewportSize({ width, height })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await mockRadar(page)
    await session(page)
    await page.goto('/')
    await expect(page.getByRole('heading', { name: '发现' })).toBeVisible()
    await expect(page.getByRole('heading', { name: '项目动态' })).toBeVisible()
    await expect(page.locator('.feature-panel').getByRole('link', { name: 'vercel/ai' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: width < 700 ? '手机导航' : '主导航' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ path: info.outputPath('discover-light.png') })
    await page.getByRole('button', { name: '切换深色主题' }).click()
    await expect(page.locator('html')).toHaveClass('dark')
    await page.screenshot({ path: info.outputPath('discover-dark.png') })
    await page.reload()
    await expect(page.locator('html')).toHaveClass('dark')
    await page.goto('/repos/1?range=30d')
    await expect(page.getByRole('heading', { name: 'vercel/ai' })).toBeVisible()
    await expect(page.getByRole('img', { name: '累计 Star 趋势，缺测点断开' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}
