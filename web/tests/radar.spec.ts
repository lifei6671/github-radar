test('公开仓库撤回后详情和趋势都停止展示旧缓存', async ({ page }) => {
  await mockRadar(page)
  await page.clock.install()
  let withdrawn = false
  await page.route('**/api/v1/public/repos/1**', async (route) => {
    if (withdrawn) return route.fulfill({ status: 404, json: { code: 'not_found' } })
    return route.fallback()
  })
  await page.goto('/repos/1')
  const repo = page.getByRole('heading', { name: 'vercel/ai', exact: true })
  await expect(repo).toBeVisible()
  await expect(page.getByRole('img', { name: '累计 Star 趋势，缺测点断开' })).toBeVisible()
  withdrawn = true
  await page.getByRole('button', { name: '30 天' }).click()
  await expect(page.getByRole('alert')).toHaveText('记录不存在或已过保留期。')
  await expect(repo).toHaveCount(0)
  await expect(page.getByRole('img', { name: '累计 Star 趋势，缺测点断开' })).toHaveCount(0)
  await page.goBack()
  await expect(page.getByRole('alert')).toHaveText('记录不存在或已过保留期。')
  await expect(repo).toHaveCount(0)
  await page.getByRole('link', { name: '技术主题', exact: true }).click()
  await expect(page.getByRole('heading', { name: '技术主题' })).toBeVisible()
  await page.clock.fastForward(21_000)
  await page.goBack()
  await expect(page.getByRole('alert')).toHaveText('记录不存在或已过保留期。')
  await expect(repo).toHaveCount(0)
})

