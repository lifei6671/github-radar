test('README 翻译的计费确认绑定所选任务', async ({ page }) => {
  const fixture = await mockRadar(page)
  await session(page)
  let release!: () => void
  const waitForNewJob = new Promise<void>((resolve) => { release = resolve })
  let oldJobRead = false
  await page.route('**/api/v1/repos/by-name/vercel/ai', async (route) => {
    const newJob = oldJobRead
    if (newJob) await waitForNewJob
    fixture.setReadme(1, {
      state: 'pending', language: 'en', complete: false, truncated: false,
      translationJobId: newJob ? 32 : 31,
    })
    await route.fallback()
  })
  await page.route(/\/api\/v1\/jobs\/(31|32)$/, (route) => {
    const id = Number(route.request().url().split('/').at(-1))
    if (id === 31) oldJobRead = true
    return route.fulfill({ json: {
      id, type: 'translate_readme', status: 'unknown', errorCode: 'ai_delivery_unknown',
      repoId: 1, attempts: 1, maxAttempts: 4,
    } })
  })
  await page.goto('/admin/repos/vercel/ai')
  await page.getByRole('button', { name: '确认并继续翻译' }).click()
  const dialog = page.getByRole('dialog', { name: '确认再次调用' })
  await expect(dialog.getByRole('button', { name: '接受可能再次计费' })).toBeEnabled()
  release()
  await expect(page.getByText('任务 #32')).toBeVisible()
  await expect(dialog.getByRole('button', { name: '接受可能再次计费' })).toBeDisabled()
})

